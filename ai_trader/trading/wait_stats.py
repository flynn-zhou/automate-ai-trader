# -*- coding: utf-8 -*-
"""空仓等待时，还要等多久？——用历史数据回答，而不是靠感觉。

为什么需要这个：
趋势策略只有 52% 的时间在场，其余时间空仓等上穿。
用户看到"空仓等待"时无法区分两种情况：
  (a) 在正常等待，历史上的等待就是这么长
  (b) 系统卡住了 / 配置错了，永远不会开仓
这两种的处置完全不同，但大屏上都是一句"空仓等待"。

所以这里给出一个可查的预期：当前偏离度下，历史上平均等多久才触发进场。

【目标不是裸均线】
  第九轮加了 0.2% 滞回带，进场条件变成 收盘 > SMA*(1+h)。
  这张表因此按【真触发线】重新生成过——不是拿"涨回裸均线"的天数充数。
  实测差别（同样的历史样本，只换目标）：
      偏离桶      裸均线   真触发线
      (-2,0]       1.3  ->   1.7 天
      (-4,-2]      5.8  ->   6.3
      (-6,-4]      9.0  ->   9.8
      (-10,-6]    10.8  ->  11.2
      (-20,-10]   14.8  ->  14.8
      (-inf,-20]  20.5  ->  20.5
  方向恒为"更晚"（这本身就是对测量的一个自洽性验证）。
  第一版我只把偏离度减去 h 再去查旧表，那只能修正跨桶的情形，
  换不出这 0.8 天——所以重算了整张表。

【数据与口径】
  来源：币安现货 4h 官方 K 线，2019-12-28 ~ 2026-11-01，14999 根（6.84 年）
  方法：只取【每段连续区间的第一根】作为独立事件；目标 = 收盘 > SMA*(1+0.2%)
  生成脚本：tools/gen_wait_hyst.py（会先复现已发布的旧表，再换目标重算）

  口径修正历史：第一版把所有落在区间内的 4h 根都当独立样本，中位数 8.5 天；
  按独立事件算是 9.0 天。重叠抽样让同一次等待被重复计入几十次，
  短等待被过度加权，中位数被系统性压低。

【怎么读这张表】
  表是单调的——越低于均线，等得越久（1.7 -> 6.3 -> 9.8 -> 11.2 -> 14.8 -> 20.5 天）。
  单调性本身是对测量的一个验证：口径错了通常不会留下这种结构。

  **这是历史频率，不是预测。** 它说的是"这种状态过去一般持续多久"，
  不是"这次一定多久"。极端行情下可以远超 P90。
"""

# 生成这张表时用的滞回半宽（%）。
# 换 h 之后表就不再精确，expected_wait 会在返回值里标 extrapolated，
# 让看板/调用方能知道这是外推，而不是静默地继续给一个偏乐观的数。
CALIBRATED_HYST_PCT = 0.2

# 偏离度分桶 -> (中位等待天数, P90 等待天数, 样本数, 最长)
# 由 tools/gen_wait_hyst.py 从官方 K 线算出，不要手改。
_BUCKETS = [
    # (下界, 上界, 中位数, P90, 样本, 最长)
    (-2.0, 0.0, 1.7, 19.7, 403, 56.2),
    (-4.0, -2.0, 6.3, 32.5, 390, 56.0),
    (-6.0, -4.0, 9.8, 35.7, 333, 55.7),
    (-10.0, -6.0, 11.2, 35.0, 249, 55.3),
    (-20.0, -10.0, 14.8, 31.8, 135, 41.8),
    (-1e9, -20.0, 20.5, 28.2, 34, 32.3),
]

SOURCE = {
    "from": "2019-12-28",
    "to": "2026-11-01",
    "bars": 14999,
    "years": 6.84,
    "method": "每段连续区间的第一根（独立事件）",
    "target": "收盘 > SMA*(1+h)",
    "hyst_pct": CALIBRATED_HYST_PCT,
}


def expected_wait(dist_pct, hyst_pct=None):
    """按当前偏离度查历史等待分布：还要多久才能【真正触发进场】？

    参数
      dist_pct  现价相对裸均线的偏离度（%），负数=低于均线。看板上的 dist_pct。
      hyst_pct  滞回带半宽（%）。默认取本表标定的 CALIBRATED_HYST_PCT。
                它只用来判断"是否已经够到触发线"，不再用来平移分桶——
                因为表本身已经按真触发线算好了。

    返回 None 表示已经够到触发线（不用等了），或数据不可用。
    返回 dict 时一定带上 source，让看板能标明这是历史频率而不是预测。

    上半带：0 <= dist < hyst_pct 时，价格已在裸均线上方但还没到触发线，
    仍然需要等待，归入 (-2,0] 桶。旧版本只要 dist >= 0 就返回 None，
    这段会被整个跳过——而那时恰恰最需要说明"还要多久"。
    """
    try:
        d = float(dist_pct)
    except (TypeError, ValueError):
        return None
    if hyst_pct is None:
        h = CALIBRATED_HYST_PCT
    else:
        try:
            h = float(hyst_pct)
        except (TypeError, ValueError):
            return None
    h = abs(h)
    if d >= h:
        return None                       # 已经够到触发线
    if d > 0:
        d = -1e-9                          # 上半带：当作"刚好低于均线"
    for lo, hi, med, p90, n, mx in _BUCKETS:
        if lo < d <= hi:
            out = {"median_days": med, "p90_days": p90,
                   "max_days": mx, "samples": n, "source": SOURCE,
                   "bucketed_dist_pct": round(d, 4)}
            # 换过 h 之后的表是外推：标出来，不要静默地给偏乐观的数。
            if abs(h - CALIBRATED_HYST_PCT) > 1e-9:
                out["extrapolated"] = True
                out["calibrated_hyst_pct"] = CALIBRATED_HYST_PCT
                out["requested_hyst_pct"] = h
            return out
    return None
