FILL_TS = 1795616400000


def _upto(ts):
    return [b for b in _BARS if b[0] <= ts]


def test_anchor_is_the_fill_bar():
    """成交那根（21:30）收盘就在买点下方 → 它就是锚点。

    用户：「本来预期收针的，但是现实是收盘跌破了，不是引针了」。
    这一根收盘 58415.70，比买点低 21.3 点，而它的成交量 5992 是前几根
    （300~800）的 7~20 倍 —— 放量清算，不是针。
    """
    # 21:35 收盘时，我们已知 21:30、21:35 两根
    r = B.assess(LEVEL, _upto(1795616700000))
    assert r.state == B.CLOSED_BELOW
    assert r.anchor_ts == 1795616400000, "锚点必须是成交那根 21:30"
    assert r.anchor_close == pytest.approx(58415.70)
    assert r.bars_since == 1, "21:35 是锚点之后第 1 根"


def test_bounce_is_a_chance_to_exit_near_the_buy_point():
    """21:35 那根收 58436.00 —— 就在买点上，这是"挑价认错"的机会。

    而 22:20 最高 58435.00：**差 2 个点**碰不到正买点。
    所以回抽位必须往前站一步（L − 0.1 ATR），否则单子永远不成交。
    """
    r = B.assess(LEVEL, _upto(1795616700000))
    assert r.exit_level < LEVEL, "回抽离场位必须在买点下方一点"
    assert LEVEL - r.exit_level == pytest.approx(0.10 * r.atr, rel=0.2)

    # 21:35 收盘 58436 ≥ 回抽位 → 应当走
    go, why = B.exit_now(r, 58436.00)
    assert go, "收盘跌破后价格回到买点附近，就该离场（用户原话）"
    assert "回抽" in why or "收盘跌破" in why

    # 22:20 最高 58435 —— 比买点低 2 点，但仍然 ≥ 回抽位 → 照样能走
    go2, _ = B.exit_now(r, 58435.00)
    assert go2, ("22:20 最高 58435 差 2 点没到买点；"
                 "挂在正买点的单不会成交，回抽位前移就是为了接住它")


def test_confirmed_break_at_the_third_bar():
    """锚点后第 3 根仍跌破 → 有效跌破。

    锚点是 21:30；不含它自己数：第 1 根 21:35、第 2 根 21:40、
    第 3 根 **21:45** —— 那根收 58296.00，仍在下方 → 确认。
    （21:50 已经是第 4 根，所以 bars_since 是 4，不是 3。）
    """
    r45 = B.assess(LEVEL, _upto(1795617300000))      # 21:45 收盘
    assert r45.bars_since == 3, "21:45 是锚点之后第 3 根"
    assert r45.state == B.CONFIRMED

    r50 = B.assess(LEVEL, _upto(1795617600000))      # 21:50 收盘
    assert r50.state == B.CONFIRMED
