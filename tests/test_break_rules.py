def test_intrabar_wick_is_not_a_break():
    """盘中插下去又收回来**不算**跌破 —— 那正是我们赌的形态。

    21:30 那根最低 58204，但收盘 58415.70 在买点下方 → 算。
    反过来，一根最低远低于买点、收盘却在买点上方的，不算。
    这条守的是"用收盘不用盘中"这个前提：拿盘中价判跌破 = 自己否决自己的策略。
    """
    lvl = 58000.0
    bars = [
        (1, 58100.0, 58150.0, 57900.0, 58080.0),   # 盘中破 58000，收盘收回
        (2, 58080.0, 58120.0, 57850.0, 58100.0),   # 又一根下影收回
    ]
    r = B.assess(lvl, bars, atr=200.0)
    assert r.state == B.INTACT, "收盘没收在下方就不算跌破"


def test_a_two_point_close_beyond_is_noise_not_a_break():
    """越过关键位只有 2 个点 → 不算跌破（噪声，不是前提被否）。

    这是从真实用例反推出来的下限：`test_run_plan_fills_the_inverse_v_on_a_
    later_5m_bar` 里成交那根收盘只比触发价高 2 点。若把缓冲去掉，
    任何一次"带着零点几个点收在另一侧"都会被判成前提被否 ——
    策略会被反复砍在噪声上，这是比爆仓更慢的死法。
    """
    bars = [(1000, 100.0, 100.5, 99.5, 100.5),
            (2000, 100.5, 100.8, 99.6, 99.98)]   # 只低 2 个点
    r = B.assess(100.0, bars, since_ts=1000)
    assert r.state == B.INTACT, ("2 点的收盘穿越被当成跌破：%s" % r.describe())


def test_history_before_entry_never_opens_the_window():
    """入场**之前**就跌破过，但那不是这笔仓的事 —— 不许一成交就出场。

    这条钉的是 `since_ts` 过滤。没有它，只要今天早些时候跌破过同一个价位，
    之后每一笔在这个价位上方成交的单都会一成交就被判"有效跌破"
    （bars_since 从那根老锚点数起，早就 ≥3）。
    """
    # 1~4 根都在下方（若不过滤，锚点在 1 号，到成交那根已经 3 根以上）
    bars = [(1000, 95.0, 95.5, 94.5, 95.0),
            (2000, 95.0, 96.5, 94.5, 96.0),
            (3000, 96.0, 97.5, 95.5, 97.0),
            (4000, 100.0, 100.2, 99.9, 100.1)]   # 成交那根：收在上方
    old = B.assess(100.0, bars)
    assert old.state == B.CONFIRMED, "对照组：不过滤时它确实会被判成有效跌破"
    r = B.assess(100.0, bars, since_ts=4000)
    assert r.state == B.INTACT, ("入场前的老跌破被算进来了：%s" % r.describe())


def test_a_new_cycle_after_reclaim():
    """收回水平位上方后，旧的跌破段作废；再破是新的一次，时钟重置。

    不重置的后果：一根老锚点会永远把后面所有行情判成"已确认"，
    变成单边看空的永久开关 —— 那会让系统再也拿不住一笔多单。
    """
    lvl = 100.0
    bars = [
        (1, 101.0, 101.5, 98.0, 99.0),     # 跌破（锚点）
        (2, 99.0, 99.5, 97.0, 98.0),
        (3, 98.0, 98.5, 96.0, 97.0),
        (4, 97.0, 100.5, 96.5, 100.2),     # 收回上方 → 段结束
    ]
    r = B.assess(lvl, bars, atr=1.0)
    assert r.state == B.INTACT, "收回上方之后不该还停在已确认"

    bars2 = bars + [
        (5, 100.2, 100.4, 99.0, 99.5),
        (6, 99.5, 99.8, 98.0, 98.5),
    ]
    r2 = B.assess(lvl, bars2, atr=1.0)
    assert r2.anchor_ts == 5, "再破要开新锚点"
    assert r2.bars_since == 1
    assert r2.state == B.CLOSED_BELOW


def test_since_ts_ignores_history_before_entry():
    """入场前的历史跌破不能算到这笔仓头上。

    不看 `since_ts` 的后果：挂单在 21:25 之前价格早就跌破过买点，
    一成交就立刻被判"已确认"并马上市价平仓 —— 开仓即平仓的死亡循环。
    """
    lvl = 58437.0
    # 假设这根仓 21:30 才成交；此前 20:30~21:25 都在买点上方
    r = B.assess(LEVEL, _upto(1795616700000), since_ts=FILL_TS)
    assert r.anchor_ts == 1795616400000

    # 反过来：把 since_ts 往前挪到更早一根，锚点仍不许早于 since_ts
    r2 = B.assess(LEVEL, _upto(1795616700000), since_ts=1795616100000)
    assert r2.anchor_ts >= 1795616100000, "锚点越过了 since_ts，用到入场前的行情"

    # 用一段"入场前就跌破"的假数据验证：since_ts 之后没有跌破 → INTACT
    bars = [
        (1000, 90.0, 91.0, 89.0, 90.0),    # 入场前，早已跌破
        (2000, 101.0, 102.0, 100.0, 101.0),  # 入场后，回到买点上方
    ]
    r3 = B.assess(100.0, bars, atr=1.0, since_ts=1500)
    assert r3.state == B.INTACT, "入场前的跌破不该被判成这笔仓的跌破"


def test_short_side_is_mirrored():
    """空头镜像：收在卖点**上方**才算跌破（即假突破失败）。"""
    lvl = 60000.0
    bars = [(1, 59800.0, 59900.0, 59700.0, 59850.0),
            (2, 59850.0, 60100.0, 59800.0, 60050.0),
            (3, 60050.0, 60200.0, 60000.0, 60150.0)]
    r = B.assess(lvl, bars, atr=200.0, direction="short")
    assert r.state == B.CLOSED_BELOW
    assert r.trigger >= lvl, "空头的触发线不该在卖点下方"
    assert r.exit_level > lvl, "空头的回抽离场位在卖点上方"
    go, _ = B.exit_now(r, 60010.0)
    assert go, "空头：价格回抽到卖点附近就该走"


def test_what_would_have_happened_on_the_real_trade():
    """把这次事故按新规则回放一遍 —— 这是全部改动的意义所在。

    真实结果：0.02 在 57454.60 被平，毛 -12.048U。
    新规则：锚点根（21:30）收盘就开钟，21:35 收盘 58436 触发回抽离场。
            系统那 0.01 在 58436 附近出场 ≈ -0.01U（几乎打平），
            而不是跟着一路跌到 57454。
    """
    r = B.assess(LEVEL, _upto(1795616700000), since_ts=FILL_TS)
    go, _ = B.exit_now(r, 58436.00)
    assert go
    # 出场价与买点只差 1 点，而不是 982 点
    assert abs(58436.00 - LEVEL) < 2.0
    naive_loss = (57454.60 - LEVEL) * 0.01
    fixed_loss = (58436.00 - LEVEL) * 0.01
    assert fixed_loss > naive_loss * 20, "新规则的亏损应当比事故小一个数量级以上"
